-- Estructura candidata: revisar antes de ejecutar. No carga datos históricos.
-- Los identificadores se escriben sin comillas y PostgreSQL los guarda en minúsculas.
create extension if not exists btree_gist with schema extensions;

create table public.hotel (
  id_hotel bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  direccion text not null check (btrim(direccion) <> ''),
  ciudad text not null check (btrim(ciudad) <> ''),
  pais text not null check (btrim(pais) <> ''),
  telefono text, email text, categoria text,
  zona_horaria text check (zona_horaria is null or btrim(zona_horaria) <> '')
);

create table public.cargo (
  id_cargo bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  salario_base numeric(10,2) not null check (salario_base >= 0 and salario_base <> 'NaN'::numeric)
);
create unique index cargo_nombre_normalizado_uq on public.cargo (lower(btrim(nombre)));

create table public.tipo_habitacion (
  id_tipo bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  descripcion text,
  capacidad integer not null check (capacidad > 0)
);
create unique index tipo_habitacion_nombre_normalizado_uq on public.tipo_habitacion (lower(btrim(nombre)));

create table public.cliente (
  id_cliente bigint generated by default as identity primary key,
  nombre text not null check (btrim(nombre) <> ''),
  apellido text not null check (btrim(apellido) <> ''),
  tipo_documento text check (tipo_documento is null or btrim(tipo_documento) <> ''),
  pais_emisor_documento text check (pais_emisor_documento is null or btrim(pais_emisor_documento) <> ''),
  documento text not null check (btrim(documento) <> ''),
  email text, telefono text, nacionalidad text
);
create unique index cliente_documento_normalizado_uq on public.cliente
  (lower(btrim(tipo_documento)), lower(btrim(pais_emisor_documento)), lower(btrim(documento)));

create table public.empleado (
  id_empleado bigint generated by default as identity primary key,
  hotel_id_hotel bigint not null references public.hotel(id_hotel) on delete restrict,
  cargo_id_cargo bigint not null references public.cargo(id_cargo) on delete restrict,
  nombre text not null check (btrim(nombre) <> ''),
  apellido text not null check (btrim(apellido) <> ''),
  documento text not null check (btrim(documento) <> ''),
  fecha_ingreso date not null
);

create table public.habitacion (
  id_habitacion bigint generated by default as identity primary key,
  hotel_id_hotel bigint not null references public.hotel(id_hotel) on delete restrict,
  tipo_habitacion_id_tipo bigint not null references public.tipo_habitacion(id_tipo) on delete restrict,
  numero text not null check (btrim(numero) <> ''),
  piso integer,
  estado text not null check (estado in ('DISPONIBLE', 'OCUPADA', 'MANTENIMIENTO'))
);
create unique index habitacion_numero_normalizado_uq on public.habitacion (hotel_id_hotel, lower(btrim(numero)));

create table public.tarifa_habitacion (
  id_tarifa bigint generated by default as identity primary key,
  hotel_id_hotel bigint not null references public.hotel(id_hotel) on delete restrict,
  tipo_habitacion_id_tipo bigint not null references public.tipo_habitacion(id_tipo) on delete restrict,
  precio_noche numeric(10,2) not null check (precio_noche > 0 and precio_noche <> 'NaN'::numeric),
  unique (hotel_id_hotel, tipo_habitacion_id_tipo)
);

create table public.servicio (
  id_servicio bigint generated by default as identity primary key,
  hotel_id_hotel bigint not null references public.hotel(id_hotel) on delete restrict,
  nombre text not null check (btrim(nombre) <> ''),
  precio numeric(10,2) not null check (precio >= 0 and precio <> 'NaN'::numeric)
);
create unique index servicio_nombre_normalizado_uq on public.servicio (hotel_id_hotel, lower(btrim(nombre)));

create table public.reserva (
  id_reserva bigint generated by default as identity primary key,
  cliente_id_cliente bigint not null references public.cliente(id_cliente) on delete restrict,
  habitacion_id_habitacion bigint not null references public.habitacion(id_habitacion) on delete restrict,
  fecha_entrada date not null,
  fecha_salida date not null,
  estado text not null check (estado in ('CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
  total_estimado numeric(10,2) not null check (total_estimado >= 0 and total_estimado <> 'NaN'::numeric),
  fecha_reserva date not null,
  check (fecha_salida > fecha_entrada),
  constraint reserva_sin_solapamiento exclude using gist (
    habitacion_id_habitacion extensions.gist_int8_ops with =,
    daterange(fecha_entrada, fecha_salida, '[)') with &&
  ) where (estado in ('CONFIRMADA', 'COMPLETADA'))
);

create table public.estadia (
  id_estadia bigint generated by default as identity primary key,
  reserva_id_reserva bigint not null unique references public.reserva(id_reserva) on delete restrict,
  empleado_id_empleado bigint references public.empleado(id_empleado) on delete restrict,
  fecha_checkin date not null,
  fecha_hora_checkin timestamptz,
  fecha_checkout date,
  fecha_hora_checkout timestamptz,
  check (fecha_checkout is null or fecha_checkout >= fecha_checkin),
  check (fecha_hora_checkout is null or fecha_checkout is not null),
  check (fecha_hora_checkout is null or fecha_hora_checkin is null or fecha_hora_checkout > fecha_hora_checkin)
);

create table public.mantenimiento (
  id_mantenimiento bigint generated by default as identity primary key,
  habitacion_id_habitacion bigint not null references public.habitacion(id_habitacion) on delete restrict,
  empleado_id_empleado bigint not null references public.empleado(id_empleado) on delete restrict,
  fecha_inicio date not null,
  fecha_fin date,
  tipo text not null check (btrim(tipo) <> ''),
  costo numeric(10,2) check (costo is null or (costo >= 0 and costo <> 'NaN'::numeric)),
  check (fecha_fin is null or fecha_fin >= fecha_inicio)
);

create table public.pago (
  id_pago bigint generated by default as identity primary key,
  reserva_id_reserva bigint not null references public.reserva(id_reserva) on delete restrict,
  fecha_pago date not null,
  fecha_hora_pago timestamptz,
  tipo_pago text check (tipo_pago is null or tipo_pago in ('ADELANTO', 'ORDINARIO')),
  monto numeric(10,2) not null check (monto > 0 and monto <> 'NaN'::numeric),
  metodo_pago text not null check (btrim(metodo_pago) <> ''),
  clave_idempotencia uuid unique
);

create table public.consumo_servicio (
  id_consumo bigint generated by default as identity primary key,
  estadia_id_estadia bigint not null references public.estadia(id_estadia) on delete restrict,
  servicio_id_servicio bigint not null references public.servicio(id_servicio) on delete restrict,
  cantidad integer not null check (cantidad > 0),
  precio_unitario_aplicado numeric(10,2) not null check (precio_unitario_aplicado >= 0 and precio_unitario_aplicado <> 'NaN'::numeric)
);

create table public.cuenta_empleado (
  auth_user_id uuid primary key references auth.users(id) on delete cascade,
  empleado_id_empleado bigint not null unique references public.empleado(id_empleado) on delete restrict,
  rol_sistema text not null check (rol_sistema in ('ADMINISTRADOR', 'RECEPCIONISTA', 'MANTENIMIENTO')),
  activo boolean not null,
  fecha_vinculacion timestamptz not null
);

create view public.v_consumo_servicio_detalle with (security_invoker = true) as
select id_consumo, estadia_id_estadia, servicio_id_servicio, cantidad,
       precio_unitario_aplicado, cantidad * precio_unitario_aplicado as subtotal
from public.consumo_servicio;

