alter table public.habitacion enable row level security;
alter table public.tarifa_habitacion enable row level security;
alter table public.servicio enable row level security;
alter table public.reserva enable row level security;
alter table public.estadia enable row level security;
alter table public.mantenimiento enable row level security;
