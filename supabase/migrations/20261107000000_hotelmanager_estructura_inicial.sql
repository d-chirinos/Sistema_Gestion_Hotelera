revoke all on public.hotel, public.cargo, public.tipo_habitacion, public.cliente,
  public.empleado, public.habitacion, public.tarifa_habitacion, public.servicio,
  public.reserva, public.estadia, public.mantenimiento, public.pago,
  public.consumo_servicio, public.cuenta_empleado, public.v_consumo_servicio_detalle
  from public, anon, authenticated;
